"""Export real API responses as JSON files for the frontend (T8 mock data).

The frontend can be built against these files today and switched to live API
calls later without changing any component, because the shape is identical.

Usage:
    python scripts/export_mocks.py [region] [budget] [crop1] [crop2] [crop3]

Writes to frontend/src/mock/ :
    meta.json, crops.json, regions.json (if the endpoint exists), field.json, plans.json,
    replay_<label>.json, whatif.json, explain_<label>.json
"""

import json
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from fastapi.testclient import TestClient

from backend.main import app

args = sys.argv[1:]
region = args[0] if len(args) > 0 else "meknes"
budget = args[1] if len(args) > 1 else "medium"
rotation = args[2:5] if len(args) >= 5 else ["durum_wheat", "chickpea", "barley"]

out_dir = REPO_ROOT / "frontend" / "src" / "mock"
out_dir.mkdir(parents=True, exist_ok=True)
client = TestClient(app)
ctx = {"field_id": region, "available_water": budget, "current_rotation": rotation}


def call(path, body):
    r = client.post(path, json=body)
    if r.status_code != 200:
        sys.exit(f"{path} -> HTTP {r.status_code}: {r.text}")
    return r.json()


def save(name, data):
    (out_dir / name).write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    print("wrote", (out_dir / name).relative_to(REPO_ROOT))


save("meta.json", {
    "note": "Generated by scripts/export_mocks.py from the real API. Same shape as live responses.",
    "request": ctx,
    "endpoints": {
        "crops": "GET /api/crops",
        "regions": "GET /api/regions",
        "field": "POST /api/field",
        "plans": "POST /api/plans",
        "replay": "POST /api/plans/{plan_id}/replay",
        "whatif": "POST /api/whatif",
        "explain": "POST /api/plans/{plan_id}/explain",
    },
})
crops_response = client.get("/api/crops")
if crops_response.status_code != 200:
    sys.exit(f"/api/crops -> HTTP {crops_response.status_code}: install T7.1 first.")
save("crops.json", crops_response.json())
regions_response = client.get("/api/regions")
if regions_response.status_code == 200:
    save("regions.json", regions_response.json())
else:
    print("note: /api/regions not found, regions.json skipped")
save("field.json", call("/api/field", {"field_id": region}))
built = call("/api/plans", ctx)
save("plans.json", built)
for p in built["plans"]:
    save(f"replay_{p['label']}.json", call(f"/api/plans/{p['plan_id']}/replay", ctx))
    save(f"explain_{p['label']}.json", call(f"/api/plans/{p['plan_id']}/explain", ctx))
ids = [p["plan_id"] for p in built["plans"]]
save("whatif.json", call("/api/whatif", {**ctx, "plan_ids": ids, "temp_delta_c": 2.0, "rain_factor": 0.7}))
print("Done. Import these files in the frontend instead of calling the API while building screens.")
